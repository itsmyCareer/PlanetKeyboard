#!/usr/bin/env python3
"""Tools/rime/chat_phrases.txt → Tools/rime/data/planet_custom_phrase.txt (Rime stabledb text).

Each multi-character chat word is pinned for its abbreviation (你好 → nh, 你在做什么 → nzzsm),
where corpus weights alone put rarer words first. Readings come from the rime-ice word lists
in Vendor/rime-ice/cn_dicts (whole word if listed, otherwise character by character).

Usage: python3 -I Tools/rime/make_custom_phrase.py [Vendor/rime-ice]
"""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ice = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "Vendor", "rime-ice")


def entries(name):
    """(text, pinyin, weight) rows of a rime-ice dictionary."""
    in_body = False
    for line in open(os.path.join(ice, "cn_dicts", f"{name}.dict.yaml"), encoding="utf-8"):
        line = line.rstrip("\n")
        if not in_body:
            in_body = line == "..."
            continue
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) >= 2 and parts[1]:
            weight = int(parts[2]) if len(parts) > 2 and parts[2].isdigit() else 0
            yield parts[0], parts[1], weight


# Best reading of each character (8105 lists every common character with weights).
char_reading, char_weight = {}, {}
for text, pinyin, weight in entries("8105"):
    if weight >= char_weight.get(text, -1):
        char_reading[text], char_weight[text] = pinyin, weight
syllables = set(char_reading.values())

word_reading, word_weight = {}, {}
for name in ("base", "ext"):
    for text, pinyin, weight in entries(name):
        if weight >= word_weight.get(text, -1):
            word_reading[text], word_weight[text] = pinyin, weight


def reading(word):
    if word in word_reading:
        return word_reading[word]
    if all(ch in char_reading for ch in word):
        return " ".join(char_reading[ch] for ch in word)
    return None


def is_full_pinyin(code):
    """Codes that are themselves full pinyin ("wa" = 晚安's initials but also the syllable wa)
    would hide the normal candidates, so they are skipped."""
    ok = [True] + [False] * len(code)
    for i in range(len(code)):
        if ok[i]:
            for j in range(i + 1, min(len(code), i + 6) + 1):
                if code[i:j] in syllables:
                    ok[j] = True
    return ok[len(code)]


words = [l.strip() for l in open(os.path.join(root, "Tools/rime/chat_phrases.txt"), encoding="utf-8")
         if l.strip() and not l.startswith("#")]
lines, missing = [], []
for rank, w in enumerate(words):
    if len(w) < 2:
        continue
    r = reading(w)
    if not r:
        missing.append(w)
        continue
    code = "".join(s[0] for s in r.split())
    if is_full_pinyin(code):
        continue
    lines.append(f"{w}\t{code}\t{1000 - rank}")

out = os.path.join(root, "Tools/rime/data/planet_custom_phrase.txt")
with open(out, "w", encoding="utf-8") as f:
    f.write("# Generated by Tools/rime/make_custom_phrase.py — do not edit.\n")
    f.write("# encoding: utf-8\n#\n# text\tcode\tweight\n")
    f.write("\n".join(lines) + "\n")
print(f"wrote {len(lines)} phrases, missing readings: {missing}")
