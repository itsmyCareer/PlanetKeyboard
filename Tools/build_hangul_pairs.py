#!/usr/bin/env python3
"""Korean word frequencies → KeyboardExtension/Resources/hangul_pairs.tsv

On 단모음 the same consonant tapped twice after a vowel is ambiguous: ㅂㅏㄱㄱㅜ can be 박구
(받침 ㄱ + 초성 ㄱ) or 바꾸 (쌍자음 ㄲ). The keyboard decides with these counts:

    <left syllable without 받침><consonant><vowel key>  \t  split count  \t  tense count

- split: words containing e.g. 박 followed by a syllable starting with ㄱ + that vowel
- tense: words containing 바 followed by a syllable starting with ㄲ + that vowel

The vowel is grouped by the first key tapped on 단모음 (ㅛ, ㅘ, ㅚ → ㅗ; ㅝ, ㅠ → ㅜ ...),
because the keyboard has to decide before the vowel is finished.

Source: hermitdave/FrequencyWords, ko_full.txt (OpenSubtitles 2018; content CC BY-SA 4.0),
downloaded by Tools/rime/fetch_sources.sh into Vendor/frequencywords.

Usage: python3 -I Tools/build_hangul_pairs.py [Vendor/frequencywords/ko_full.txt]
"""
import os
import sys
from collections import defaultdict

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "Vendor", "frequencywords", "ko_full.txt")
out = os.path.join(root, "KeyboardExtension", "Resources", "hangul_pairs.tsv")

INITIALS = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ"
MEDIALS = "ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ"
FINALS = [""] + list("ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ")
DOUBLE = {"ㄱ": "ㄲ", "ㄷ": "ㄸ", "ㅂ": "ㅃ", "ㅅ": "ㅆ", "ㅈ": "ㅉ"}
VOWEL_KEY = {"ㅑ": "ㅏ", "ㅒ": "ㅐ", "ㅕ": "ㅓ", "ㅖ": "ㅔ", "ㅘ": "ㅗ", "ㅙ": "ㅗ", "ㅚ": "ㅗ",
             "ㅛ": "ㅗ", "ㅝ": "ㅜ", "ㅞ": "ㅜ", "ㅟ": "ㅜ", "ㅠ": "ㅜ", "ㅢ": "ㅡ"}
MIN_COUNT = 1          # every word in the list
MIN_TOTAL = 3          # drop rows seen only once or twice


def split(syllable):
    code = ord(syllable) - 0xAC00
    if not 0 <= code < 11172:
        return None
    return INITIALS[code // 588], MEDIALS[code % 588 // 28], FINALS[code % 28]


def compose(initial, medial, final=""):
    return chr(0xAC00 + (INITIALS.index(initial) * 21 + MEDIALS.index(medial)) * 28 + FINALS.index(final))


counts = defaultdict(lambda: [0, 0])
for line in open(src, encoding="utf-8"):
    parts = line.split()
    if len(parts) != 2 or not parts[1].isdigit():
        continue
    word, n = parts[0], int(parts[1])
    if n < MIN_COUNT:
        continue
    for a, b in zip(word, word[1:]):
        ja, jb = split(a), split(b)
        if not ja or not jb:
            continue
        vowel = VOWEL_KEY.get(jb[1], jb[1])
        if ja[2] in DOUBLE and jb[0] == ja[2]:                       # 박 + 구 → split
            counts[compose(ja[0], ja[1]) + ja[2] + vowel][0] += n
        elif ja[2] == "" and jb[0] in DOUBLE.values():               # 바 + 꾸 → tense
            plain = next(k for k, v in DOUBLE.items() if v == jb[0])
            counts[a + plain + vowel][1] += n

rows = sorted((k, s, t) for k, (s, t) in counts.items() if s + t >= MIN_TOTAL)
with open(out, "w", encoding="utf-8") as f:
    f.write("# Generated by Tools/build_hangul_pairs.py from FrequencyWords ko_full.txt "
            "(Hermit Dave, CC BY-SA 4.0) — do not edit.\n")
    f.write("# key = left syllable + consonant + vowel key; split count; tense count\n")
    for k, s, t in rows:
        f.write(f"{k}\t{s}\t{t}\n")
total_split = sum(s for _, s, _ in rows)
total_tense = sum(t for _, _, t in rows)
print(f"wrote {len(rows)} rows to {out} (split {total_split}, tense {total_tense})")
